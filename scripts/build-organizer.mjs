import fs from 'node:fs';
import {renderRegionIndex} from './region-index.mjs';
const root = new URL('../', import.meta.url);
const read = path => fs.readFileSync(new URL(path, root), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n';
const data = JSON.parse(read('sources/naming/region-data.json'));
const source = '// SPDX-License-Identifier: GPL-3.0-only\n// Generated by scripts/build-organizer.mjs. Independent backend subscription pipeline.\n'
  + '// Naming/region data: GUI.for.Cores Plugin-Hub @ 205ecacb0742a185947252cb91e5b11541c32a94.\n'
  + '// See sources/naming/NOTICE.md and docs/migration-1.4.md. No desktop store or metadata refilter.\n\n'
  + read('sources/naming/shared.js') + '\n'
  + 'const RegionData = ' + JSON.stringify(data) + ';\n'
  + renderRegionIndex(data) + '\n'
  + read('sources/naming/regions.js') + '\n'
  + read('sources/naming/plugin-index-the-proxy-name.js').replace('function onSubscribe(', 'function legacyIndex(') + '\n'
  + read('sources/naming/plugin-modify-proxy-name.js').replace('function onSubscribe(', 'function legacyFlags(') + '\n'
  + read('sources/naming/plugin-beautiful-node-name.js').split('function onSubscribe(')[0] + '\n'
  + read('sources/naming/organizer.js');
const output = new URL('plugins/plugin-subscription-organizer.js', root);
if (Buffer.byteLength(source, 'utf8') > 256 * 1024) throw new Error('subscription organizer exceeds host source limit');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== source) throw new Error('subscription organizer generated source is stale');
} else fs.writeFileSync(output, source);
