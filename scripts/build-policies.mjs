import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const read = path => fs.readFileSync(new URL(path, root), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n';
for (const kind of ['dns', 'client']) {
  const source = '// SPDX-License-Identifier: GPL-3.0-only\n// Generated by scripts/build-policies.mjs. No host, filesystem or network access.\n'
    + '// Field semantics: https://github.com/SagerNet/sing-box/blob/v1.14.2/option/' + (kind === 'dns' ? 'rule_dns.go' : 'rule.go') + '\n'
    + '// Independent implementation; see docs/policies.md. Existing services/targets are never created.\n\n'
    + read('sources/policy/common.js') + '\n' + read('sources/policy/' + kind + '.js');
  const output = new URL('plugins/plugin-' + kind + '-policy.js', root);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8') !== source) throw new Error(kind + ' policy generated source is stale');
  } else fs.writeFileSync(output, source);
}
// The legacy TUN option remains readable, with the same CIDR overlap check in
// either plugin order. No runtime dependency between standalone scripts.
const common = read('sources/policy/common.js');
const migration = common.slice(common.indexOf('function ipBytes('), common.indexOf('function strings('))
  .replace(/\bipBytes\b/g, 'migrationIPBytes').replace(/\bcidr\b/g, 'migrationCIDR').replace(/\boverlaps\b/g, 'migrationOverlaps');
const tun = '// SPDX-License-Identifier: GPL-3.0-only\n// Generated by scripts/build-policies.mjs; edit sources/policy/tun.js.\n'
  + read('sources/policy/tun.js') + '\n' + migration;
const tunOutput = new URL('plugins/plugin-router-transparent-proxy.js', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(tunOutput, 'utf8') !== tun) throw new Error('TUN generated source is stale');
} else fs.writeFileSync(tunOutput, tun);
