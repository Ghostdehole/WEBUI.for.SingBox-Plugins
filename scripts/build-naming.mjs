import fs from 'node:fs';
const sources = new URL('../sources/naming/', import.meta.url);
const targets = new URL('../plugins/', import.meta.url);
const ids = ['plugin-index-the-proxy-name', 'plugin-modify-proxy-name', 'plugin-beautiful-node-name'];
const read = name => fs.readFileSync(new URL(name, sources), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n';
const data = JSON.parse(read('region-data.json'));
const header = '// SPDX-License-Identifier: GPL-3.0-only\n// WEBUI.for.SingBox router script plugin.\n'
  + '// Generated by scripts/build-naming.mjs; edit sources/naming instead.\n'
  + '// Region data/aliases adapted from GUI.for.Cores and Plugin-Hub contributors,\n'
  + '// GUI-for-Cores/Plugin-Hub @ 205ecacb0742a185947252cb91e5b11541c32a94.\n'
  + '// Sources: plugins/Generic/plugin-beautiful-node-name.js (RegionData),\n'
  + '// plugins/Generic/plugin-modify-proxy-name.js and plugin-index-the-proxy-name.js.\n'
  + '// See sources/naming/NOTICE.md for attribution and adaptation details.\n';
let stale = false;
for (const id of ids) {
  const source = header + '\n' + read('shared.js') + '\n'
    + (id === ids[0] ? '' : 'const RegionData = ' + JSON.stringify(data) + ';\n\n' + read('regions.js') + '\n')
    + read(id + '.js');
  const path = new URL(id + '.js', targets);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(path, 'utf8') !== source) { console.error(id + ': generated source is stale'); stale = true; }
  } else fs.writeFileSync(path, source);
}
if (stale) process.exitCode = 1;
